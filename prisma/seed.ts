async function main() {
  console.log('→ Сидинг базы данных...')

  // 1. Администратор
  const adminEmail = process.env.ADMIN_EMAIL || 'admin@example.com'
  const adminPassword = process.env.ADMIN_PASSWORD || 'ChangeMe2026!'
  const existing = await db.adminUser.findUnique({ where: { email: adminEmail } })
  if (!existing) {
    await db.adminUser.create({
      data: { email: adminEmail, passwordHash: hashPassword(adminPassword), name: 'Администратор' },
    })
    console.log(`✓ Администратор создан: ${adminEmail}`)
    if (!process.env.ADMIN_PASSWORD) {
      console.log('  ⚠ Пароль по умолчанию "ChangeMe2026!" — ОБЯЗАТЕЛЬНО смените его после первого входа')
      console.log('    или задайте ADMIN_PASSWORD перед сидингом. Подробности: docs/SECURITY.md')
    }
  } else {
    console.log(`• Администратор ${adminEmail} уже существует`)
  }

  // 2. Категории
  for (const c of CATEGORIES) {
    await db.category.upsert({
      where: { slug: c.slug },
      update: {},
      create: { ...c },
    })
  }
  console.log(`✓ Категории: ${CATEGORIES.length}`)

  // 3. Настройки
  for (const [key, value] of Object.entries(SETTINGS)) {
    await db.setting.upsert({ where: { key }, update: {}, create: { key, value } })
  }
  console.log(`✓ Настройки: ${Object.keys(SETTINGS).length}`)

  // 4. Тестовые статьи
  const now = new Date()
  for (const a of TEST_ARTICLES) {
    const category = await db.category.findUnique({ where: { slug: a.slugCategory } })
    if (!category) continue
    const exists = await db.article.findUnique({ where: { slug: a.slug } })
    if (exists) continue
    await db.article.create({
      data: {
        slug: a.slug,
        title: a.title,
        excerpt: a.excerpt,
        contentHtml: a.html,
        contentPlain: a.html.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim(),
        categoryId: category.id,
        tags: a.tags,
        authorName: 'Редакция проекта',
        legalBasis: a.legalBasis,
        status: 'PUBLISHED',
        isTest: true,
        views: Math.floor(Math.random() * 40) + 3,
        publishedAt: now,
        checkedAt: now,
      },
    })
  }
  console.log(`✓ Тестовые статьи: ${TEST_ARTICLES.length} (помечены флагом «тестовая», удаляются в админ-панели)`)

  console.log('✓ Сидинг завершён')
}

main()
  .catch((e) => {
    console.error(e)
    process.exit(1)
  })
  .finally(() => db.$disconnect())
