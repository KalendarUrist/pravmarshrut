import { getSettings } from '@/lib/settings'
import { sanitizeHtmlContent } from '@/lib/content'
import { Breadcrumbs } from '@/components/site/breadcrumbs'
import { AlertTriangle, ShieldCheck } from 'lucide-react'

export interface LegalPageProps {
  htmlKey: 'privacyHtml' | 'consentHtml' | 'termsHtml'
  reviewedKey: 'privacyReviewed' | 'consentReviewed' | 'termsReviewed'
  title: string
  slug: 'privacy' | 'consent' | 'terms'
}

/** Шаблоны юридических документов. Это заготовки: администратор обязан
 *  адаптировать их под свой проект и отметить проверку в админ-панели. */
export function legalTemplate(slug: string, siteName: string): string {
  if (slug === 'privacy') {
    return `
<h2>1. Общие положения</h2>
<p>Настоящая политика обработки персональных данных составлена в соответствии с Федеральным законом от 27.07.2006 № 152-ФЗ «О персональных данных» и определяет порядок обработки персональных данных и меры по обеспечению их безопасности, принимаемые владельцем сайта «${siteName}» (далее — Оператор).</p>
<h2>2. Какие данные обрабатываются</h2>
<ul>
<li>имя, указанное в форме обратной связи;</li>
<li>номер телефона и/или адрес электронной почты для ответа;</li>
<li>содержание обращения и тема вопроса;</li>
<li>технические данные: IP-адрес, сведения о браузере (в объёме, необходимом для защиты от спама и обеспечения безопасности).</li>
</ul>
<h2>3. Цели обработки</h2>
<p>Персональные данные обрабатываются исключительно для ответа на обращения пользователей и ведения переписки по вопросам, указанным в форме обратной связи. Данные не передаются третьим лицам, за исключением случаев, предусмотренных законодательством РФ.</p>
<h2>4. Сроки обработки и хранение</h2>
<p>Данные хранятся не дольше, чем этого требуют цели обработки. Обращения и связанные с ними данные удаляются по достижении целей обработки либо по запросу пользователя, за исключением данных, срок хранения которых установлен законом.</p>
<h2>5. Права пользователя</h2>
<p>Пользователь вправе получить информацию об обработке своих персональных данных, требовать их уточнения, блокирования или уничтожения, а также отозвать согласие на обработку, направив обращение через форму обратной связи на сайте.</p>
<h2>6. Файлы cookie</h2>
<p>Сайт может использовать файлы cookie для корректной работы интерфейса и (при подключении) систем веб-аналитики. Пользователь может отключить cookie в настройках браузера; часть функций сайта при этом может работать некорректно.</p>
<h2>7. Изменения политики</h2>
<p>Оператор вправе обновлять настоящую политику. Актуальная редакция всегда размещается на этой странице.</p>
`
  }
  if (slug === 'consent') {
    return `
<h2>Согласие на обработку персональных данных</h2>
<p>Оставляя обращение через форму на сайте «${siteName}», я даю согласие владельцу сайта на обработку моих персональных данных: имени, номера телефона и/или адреса электронной почты, содержания обращения.</p>
<h2>Объём и цели</h2>
<p>Согласие даётся на обработку указанных данных в целях подготовки и направления ответа на моё обращение, а также последующей связи со мной по существу заданного вопроса.</p>
<h2>Действия с данными</h2>
<p>Обработка включает сбор, запись, систематизацию, накопление, хранение, уточнение, использование, блокирование, удаление и уничтожение — с использованием средств автоматизации и без них.</p>
<h2>Срок действия и отзыв</h2>
<p>Согласие действует до достижения целей обработки. Я вправе отозвать согласие, направив обращение через форму обратной связи с пометкой «отзыв согласия». Отзыв влечёт прекращение обработки, за исключением случаев, предусмотренных законом.</p>
<p>Отправка формы подтверждает, что я ознакомлен(а) с настоящим согласием и <a href="/privacy/">политикой конфиденциальности</a> и даю согласие добровольно.</p>
`
  }
  return `
<h2>1. Предмет соглашения</h2>
<p>Настоящее соглашение регулирует использование сайта «${siteName}». Используя сайт, пользователь принимает условия настоящего соглашения. Если условия не принимаются — сайт не должен использоваться.</p>
<h2>2. Характер информации</h2>
<p>Материалы сайта носят информационно-справочный характер, описывают общие правовые ситуации и не являются юридической консультацией в отношении конкретного дела. Применение материалов без анализа конкретной ситуации может привести к неверным решениям. За консультацией по конкретной ситуации обратитесь через форму на сайте или к юристу по вашему выбору.</p>
<h2>3. Ответственность</h2>
<p>Владелец сайта стремится к актуальности материалов, однако не гарантирует соответствие материалов действующему законодательству на момент прочтения. Нормы права изменяются; в каждом материале указаны дата публикации и дата последней проверки.</p>
<h2>4. Интеллектуальные права</h2>
<p>Материалы сайта охраняются авторским правом. Разрешается цитирование с указанием активной ссылки на источник. Копирование материалов целиком в коммерческих целях без разрешения правообладателя не допускается.</p>
<h2>5. Персональные данные</h2>
<p>Обращение через формы сайта осуществляется на условиях <a href="/consent/">согласия на обработку персональных данных</a> и в соответствии с <a href="/privacy/">политикой конфиденциальности</a>.</p>
<h2>6. Изменение условий</h2>
<p>Владелец сайта вправе изменять настоящее соглашение. Актуальная редакция размещается на этой странице.</p>
`
}

/** Общий каркас юридической страницы (metadata оформляется в самой странице). */
export async function LegalPageBody({ htmlKey, reviewedKey, title, slug }: LegalPageProps) {
  const settings = await getSettings()
  const reviewed = settings[reviewedKey] === 'true'
  const html = sanitizeHtmlContent(settings[htmlKey] || legalTemplate(slug, settings.siteName))

  return (
    <div className="container-site py-6">
      <Breadcrumbs items={[{ title }]} />
      <h1 className="mt-4 font-serif text-3xl font-bold tracking-tight text-primary">{title}</h1>

      {reviewed ? (
        <p className="mt-4 inline-flex items-center gap-2 rounded-md border border-green-700/30 bg-green-50 px-3 py-2 text-xs text-green-900">
          <ShieldCheck className="h-4 w-4" aria-hidden />
          Документ адаптирован владельцем сайта и отмечен как проверенный в панели управления.
        </p>
      ) : (
        <p className="mt-4 flex items-start gap-2 rounded-md border bg-secondary/60 px-3 py-2.5 text-xs leading-relaxed text-muted-foreground">
          <AlertTriangle className="mt-0.5 h-4 w-4 shrink-0 text-gold" aria-hidden />
          <span>
            Это шаблон документа, подготовленный вместе с сайтом. Он <strong>не проверен юристом</strong>:
            перед запуском проекта адаптируйте текст под свои обстоятельства и отметьте проверку в админ-панели
            (Настройки → Юридические документы).
          </span>
        </p>
      )}

      <div className="article-content mt-6" dangerouslySetInnerHTML={{ __html: html }} />
    </div>
  )
}
